#!/usr/bin/env node
// Static site generator, replacing `gatsby build`. Renders every page in
// src/lib/routes.js to dist/<route>/index.html, inlines the CSS, emits the
// sitemap and 404.html, generates the client scripts, and copies static/.
// See docs/simplification-plan.md, Phase 1.
import * as esbuild from 'esbuild'
import { createHash } from 'node:crypto'
import { realpathSync as fs_realpath } from 'node:fs'
import os from 'node:os'
import { cp, mkdir, readFile, readdir, rename, rm, stat, unlink, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { OG_SITE_QUARTET } from '../src/lib/site.js'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
// this file's own bytes, so the SVG cache invalidates whenever the pipeline
// that filled it changes
const BUILD_SOURCE = await readFile(fileURLToPath(import.meta.url), 'utf8');
// ... and the exact dependency tree, via package-lock.json. Hashing the two
// top-level versions was not enough: svgo declares its own dependencies as
// ranges, and csso/css-tree are what actually re-serialize the path data. An
// `npm update` can move one inside svgo's range while package.json, build.mjs
// and svgo's own version all stay put -- leaving every cache key valid and the
// build emitting bytes from the old dependency until someone edits this file.
// The lockfile changes exactly when any resolved version does.
//
// It is over-eager in the other direction (a react bump invalidates all 54
// drawings), which is the same trade as hashing this file: a wasted rebuild
// costs 4 seconds, and a stale drawing ships.
async function svg_tool_fingerprint(){
    for (const f of ['package-lock.json', 'package.json']){
        try { return await readFile(path.join(root, f), 'utf8'); }
        catch { /* try the next one */ }
    }
    return 'no lockfile';
}
const SVG_TOOLS = await svg_tool_fingerprint();

// Where the site is written. Defaults to dist/, which is what netlify.toml
// publishes; the argument exists so a test can build somewhere else instead of
// mutating the tree every other test is reading.
//
// It is validated because build() opens by recursively removing this path with
// force: true. Before the argument existed that was a hardcoded gitignored
// constant; now it is the first argument to a routine command.

// resolve symlinks as far as the path actually exists, so that comparing two
// paths compares the same thing. macOS matters here: os.tmpdir() is /var/...,
// a symlink to /private/var/..., and mkdtemp hands back the unresolved form.
function real(p){
    let head = path.resolve(p), tail = '';
    for (;;){
        try { return path.join(fs_realpath(head), tail); }
        catch {
            const parent = path.dirname(head);
            if (parent === head) return path.resolve(p); // nothing exists; use it as given
            tail = path.join(path.basename(head), tail);
            head = parent;
        }
    }
}

function output_dir(arg){
    if (!arg) return path.join(root, 'dist');
    const out = path.resolve(arg);
    const under = parent => {
        const rel = path.relative(real(parent), real(out));
        return rel !== '' && !rel.startsWith('..') && !path.isAbsolute(rel);
    };
    // An allowlist, not a containment check. "Inside the repo" is far too
    // wide: `npm run build -- static` would recursively delete the 54
    // drawings, the icon set and the share cards -- the last two needing
    // rsvg-convert and pngquant to regenerate -- and `-- .git` is not
    // recoverable at all. A stray tab-complete reaches both. The only
    // intended outputs are dist/ and a scratch directory, so say exactly that.
    const ok = under(os.tmpdir())
        || (under(root) && path.basename(out).startsWith('dist'));
    if (!ok){
        throw new Error(`refusing to build into ${out}: it is deleted before the`
            + ' build starts, so it must be under ' + os.tmpdir()
            + ', or inside the repo with a name beginning "dist"');
    }
    return out;
}

const dist = output_dir(process.argv[2]);
const cache = path.join(root, '.cache'); // gitignored; may hold stale Gatsby output
// scratch, namespaced by output, so two builds with different outputs do not
// overwrite each other's SSR bundle
const ssr = path.join(cache, 'ssg-' + path.basename(dist).replace(/[^\w.-]/g, '_'));
const svg_cache = path.join(cache, 'svg');

// what ships to browsers (client JS + CSS); explicit so syntax lowering and
// CSS prefixing (e.g. -webkit-sticky for Safari <= 12) are a choice, not an
// accident of esbuild's defaults
const BROWSER_TARGET = ['chrome80', 'edge80', 'firefox75', 'safari12'];

// Share cards are generated by scripts/make-og.mjs and committed (Netlify has
// no rsvg-convert), so this build only copies them -- which means the size gate
// has to be re-applied here or a hand-edited or stale oversized card ships
// unnoticed. Over ~300 KB, iMessage/WhatsApp/Slack quietly skip the image and
// the link previews as a grey box, with nothing in any log to say so. Keep in
// sync with MAX_BYTES in scripts/make-og.mjs.
const OG_MAX_BYTES = 250_000;

// What make-og.mjs last drew on the site-wide card. In assets/ rather than
// static/og/ because it is a build-time record, not a file the site serves.
const OG_QUARTET_RECORD = path.join(root, 'assets', 'og-quartet.json');

async function check_og_cards(dir){
    const cards = (await readdir(dir)).filter(f => f.endsWith('.png'));
    if (cards.length === 0){
        throw new Error(`no share cards in ${dir}: run \`npm run og\``);
    }
    for (const card of cards){
        const { size } = await stat(path.join(dir, card));
        if (size > OG_MAX_BYTES){
            throw new Error(`og/${card} is ${size} bytes (> ${OG_MAX_BYTES}); `
                + 'rerun `npm run og` or simplify the card layout');
        }
    }

    // og.png is committed, so nothing here can see who is painted on it -- but
    // its og:image:alt is derived from OG_SITE_QUARTET. Edit that list, skip
    // `npm run og`, and the site ships a picture whose alt text names someone
    // who is not in it. make-og.mjs records what it drew; this is the check.
    const drawn = await readFile(OG_QUARTET_RECORD, 'utf8').then(JSON.parse).catch(() => null);
    if (JSON.stringify(drawn) !== JSON.stringify(OG_SITE_QUARTET)){
        throw new Error(`static/og/og.png was drawn from ${JSON.stringify(drawn)}, but `
            + `OG_SITE_QUARTET is ${JSON.stringify(OG_SITE_QUARTET)}: run \`npm run og\``);
    }

    return cards.length;
}

// The portraits are Inkscape output and they are the biggest thing the site
// ships: 2.5 MB as authored, 91,000 coordinate pairs, for drawings shown at
// most 600 CSS px. This is where the home page's weight lives.
//
// THE BIGGEST SIZE THESE ARE EVER DRAWN is the composer page portrait:
// `height: 600px` in composer.module.css above 800px wide, which is 1,800
// device pixels on a 3x phone. Not the home grid's 200px -- that is the most
// frequent size, not the largest. work.js draws 300px and the signatures top
// out at 100px. If those CSS values change, the budget below changes with them.
//
// Three steps, and the middle one is the whole trick:
//
//  1. svgo, to normalise the document and collapse Inkscape's nested groups.
//     It pushes their transforms down onto each <path> but will NOT fold them
//     into the coordinates, because these paths contain elliptical arcs and the
//     matrix reflects -- arc flags would need adjusting and it declines rather
//     than get that wrong. So every file comes out of svgo with its coordinates
//     still in a space up to 8x larger than its own viewBox, which costs a
//     digit or two on each of thousands of numbers, and with a transform
//     attribute repeated on every path.
//
//  2. Fold those transforms in ourselves (svgpath knows the arc maths), then
//     scale every drawing into one coordinate space. Both are visual no-ops.
//     After this, and only after this, "round to N decimal places" means the
//     same thing in all 54 files -- before, it meant whatever each file's
//     leftover transform made it mean.
//
//  3. svgo again, now able to round to plain integers.
//
// Scaling the viewBox and the path data together, and leaving width/height
// alone, is deliberate: 10 of the 54 files have width/height ratios that
// disagree with their viewBox, so they are meant to render letterboxed, and
// rewriting those attributes silently un-letterboxes them (Grieg by 31%).
//
// Result, over the wire: the 36 images the home page loads go from 436 KB as
// authored to 219 KB, and all 54 from 855 KB to 405 KB. Error is 1/16384 of
// each drawing's height, ~0.11px at the 1,800px maximum above -- four times
// tighter than the previous approach managed at 286 KB.
//
// Verified rather than argued, and worth redoing if these numbers are touched:
// all 54 rasterized against the authored originals at 600, 900 and 1,800px and
// compared channel by channel. Mean 0.65-0.92% of pixels differ, worst file
// 3.3%, all of it edge antialiasing, and the worst case is indistinguishable
// side by side at 6x magnification.
//
// Run here rather than committed, unlike the icons and share cards -- those are
// committed because Netlify has neither rsvg-convert nor pngquant, whereas svgo
// and svgpath are pure JS. So static/ keeps the original drawings and there is
// no 54-file diff whenever the artwork changes. Both are real dependencies, not
// devDependencies: `npm run build` needs them and Netlify runs `npm run build`.

// One coordinate space for every drawing, tall enough that integer coordinates
// land well inside a pixel at the largest size the site draws (1,800 device px
// / 16384 = 0.11 px).
const SVG_UNITS = 16384;

const VIEWBOX = /viewBox\s*=\s*"\s*([-\d.eE]+)[,\s]+([-\d.eE]+)[,\s]+([-\d.eE]+)[,\s]+([-\d.eE]+)\s*"/;
const PATH_TAG = /<path\b[^>]*>/g;

// Fold each path's transform into its own coordinates, then put every drawing
// in an SVG_UNITS-tall space. Both leave the rendering identical.
function normalize_svg(text, name){
    const vb = VIEWBOX.exec(text);
    if (!vb) throw new Error(`${name} has no viewBox to normalize against`);
    const [, x, y, w, h] = vb.map(Number);
    const k = SVG_UNITS / Math.abs(h);

    text = text.replace(PATH_TAG, tag => {
        const d = /\sd="([^"]*)"/.exec(tag);
        if (!d) return tag;
        const t = /\stransform="([^"]*)"/.exec(tag);
        let p = svgpath(d[1]);
        // .transform() understands the SVG transform grammar, and its arc
        // handling is why this is not hand-rolled: under a reflection the
        // sweep flag has to flip, and under a non-uniform scale the arc has
        // to become curves. Getting either wrong is silent and ugly.
        // a path may legitimately arrive with no transform of its own; if one
        // was left on an ancestor instead, the whole-document check below
        // catches it, which is why there is no counter here
        if (t) p = p.transform(t[1]);
        const folded = p.scale(k).abs().round(4).toString();
        const out = t ? tag.slice(0, t.index) + tag.slice(t.index + t[0].length) : tag;
        const d2 = /\sd="([^"]*)"/.exec(out);
        return out.slice(0, d2.index + d2[0].indexOf('"') + 1) + folded
             + out.slice(d2.index + d2[0].length - 1);
    });

    // ANY surviving transform, not just one on a <path>. svgo does not always
    // push a group transform down: collapseGroups and moveGroupAttrsToElems
    // bail when the <g> also carries clip-path, mask, filter, opacity or a
    // style it cannot merge. A transform left on an ancestor still applies
    // after this function has scaled the path data and the viewBox, and any
    // translate in it is then unscaled -- a drawing rendered at the wrong
    // offset, with nothing to notice it. Stop instead.
    if (/\stransform=/.test(text)){
        throw new Error(`${name} still has a transform after folding`);
    }

    // Only <path> coordinates are scaled above, but the viewBox is scaled for
    // the whole document, so any other geometry would keep its old coordinates
    // inside a viewBox up to 26x larger and render tiny in the corner. All 54
    // drawings reduce to paths today, and preset-default does NOT convert
    // <circle>/<ellipse> (that needs convertArcs) or <rect rx>, so the first
    // drawing that contains one has to fail here rather than ship wrong.
    const FOLDABLE = new Set(['svg', 'g', 'defs', 'path']);
    for (const [, el] of text.matchAll(/<([a-zA-Z][\w:-]*)/g)){
        if (!FOLDABLE.has(el)){
            throw new Error(`${name} contains <${el}>, whose coordinates this`
                + ' does not scale; only <path> geometry can be normalized');
        }
    }

    // Same reasoning, for geometry that is not in the `d` attribute at all.
    // Scaling the path data and the viewBox together is a visual no-op only
    // for what the path data expresses; stroke-width, stroke-dasharray,
    // stroke-dashoffset and stroke-miterlimit are in user units *outside* it,
    // so they would keep their old magnitude in a space up to 966x larger --
    // a stroke k times too thin, which at these factors means invisible.
    //
    // Every drawing is fill-only today (`stroke:none`), so this has never
    // fired. It is here because the failure is silent and every existing test
    // would still pass: no transform survives, the viewBox is 16384, the file
    // is smaller. Scaling the stroke properties alongside the coordinates
    // would also be correct, and is the right fix if stroked artwork ever
    // turns up -- refusing is simply the honest version of "not handled".
    const stroked = /stroke\s*[:=]\s*"?\s*(?!none\b)[^;"'\s]/i.exec(text);
    if (stroked){
        throw new Error(`${name} has a stroke (${stroked[0].trim()}...), whose width this`
            + ' does not scale; only fill-only drawings can be normalized');
    }
    const scaled = `viewBox="${(x*k).toFixed(4)} ${(y*k).toFixed(4)} `
                 + `${(w*k).toFixed(4)} ${(h*k).toFixed(4)}"`;
    return text.slice(0, vb.index) + scaled + text.slice(vb.index + vb[0].length);
}

// svgo costs ~170ms just to import, which is a third of a warm build, and a
// warm build never calls it. Loaded on first use instead.
let svgo, svgpath;
async function load_svg_tools(){
    if (!svgo) ({ optimize: svgo } = await import('svgo'));
    if (!svgpath) ({ default: svgpath } = await import('svgpath'));
}

function svgo_pass(source, file, digits){
    return svgo(source, {
        path: file,
        multipass: true, // one pass leaves work on the table on files this shape
        plugins: [{ name: 'preset-default', params: { overrides: {
            convertPathData: { floatPrecision: digits, transformPrecision: 5,
                               applyTransforms: true },
            // never 0: this rounds numeric attributes outside the path data,
            // where an integer can visibly change a small value. It is not a
            // safety net for stroke geometry -- a stroke would already have
            // been divided by k before reaching here, which is why
            // normalize_svg refuses one outright.
            cleanupNumericValues: { floatPrecision: Math.max(digits, 2) },
        } } }],
    }).data;
}

// Two full svgo passes over 54 drawings costs ~3.3s, which turned a 0.5s build
// into a 5s one -- and `npm test` shells out to four builds, so it felt like
// five seconds turning into forty. The work is worth it (structure-only pass 1
// was tried: 1.8s cheaper and 32% *bigger* over the wire, because pass 1's path
// re-encoding is what lets pass 2 pack well), so it is cached rather than cut.
//
// Keyed on the drawing's own bytes plus scripts/build.mjs itself. Hashing this
// file is deliberately over-eager -- any edit here busts every entry -- but it
// means nobody has to remember to bump a version constant after changing the
// pipeline, which is exactly the mistake that would ship stale artwork.
function cache_key(source){
    return createHash('sha256')
        .update(BUILD_SOURCE).update('\0').update(SVG_TOOLS).update('\0').update(source)
        .digest('hex').slice(0, 32) + '.svg';
}

// Every edit to this file changes BUILD_SOURCE and so changes all 54 keys.
// Without pruning the cache grows by ~1.1 MB per revision of the build and
// never shrinks -- measured: 54 entries became 162 after two trivial edits.
// So each build drops whatever it did not use. Nothing here is precious; a
// wrong prune costs one slow build.
const TMP_GRACE_MS = 60 * 60 * 1000;

async function prune_svg_cache(keep){
    for (const f of await readdir(svg_cache).catch(() => [])){
        if (keep.has(f)) continue;
        // Never young .tmp files: cached_svg writes <key>.svg.<pid>.tmp and
        // renames it, and `keep` only ever holds final names. Deleting one
        // mid-flight made the *other* build's rename fail with ENOENT and exit
        // non-zero -- which is exactly the concurrent case CLAUDE.md now
        // advertises as safe. Old ones are the debris of a build that died
        // between write and rename, and those are worth collecting.
        if (f.endsWith('.tmp')){
            const age = await stat(path.join(svg_cache, f))
                .then(s => Date.now() - s.mtimeMs).catch(() => 0);
            if (age < TMP_GRACE_MS) continue;
        }
        await unlink(path.join(svg_cache, f)).catch(() => {});
    }
}

async function cached_svg(source, transform){
    const hit = path.join(svg_cache, cache_key(source));
    try {
        return await readFile(hit, 'utf8');
    } catch {
        await load_svg_tools();
        const data = transform();
        await mkdir(svg_cache, { recursive: true });
        // temp-then-rename, because writeFile truncates and then streams: a
        // Ctrl-C, crash or full disk in between leaves a short file under a
        // content-addressed name, and every later build would read that
        // truncated drawing and ship it. Nothing downstream would notice --
        // the viewBox is in the first few hundred bytes, so both SVG tests
        // still pass on a portrait missing half its paths. rename() is atomic
        // within a filesystem, which also makes a concurrent reader safe.
        const tmp = `${hit}.${process.pid}.tmp`;
        await writeFile(tmp, data);
        // the cache is advisory and `data` is already in hand, so losing a
        // race here costs one recomputation next time, not a failed build
        await rename(tmp, hit).catch(() => unlink(tmp).catch(() => {}));
        return data;
    }
}

// static/*.svg -> dist/*.svg. Reads the source and writes the output, the way
// esbuild does for JS and CSS -- it used to let cp() copy all 54 drawings and
// then rewrite them in place, which meant 2.5 MB of copying thrown away, and a
// step whose input was its own output.
async function minify_svgs(src_dir, out_dir){
    const names = (await readdir(src_dir)).filter(f => f.endsWith('.svg'));
    const keep = new Set();
    let before = 0, after = 0, copied = 0;
    for (const name of names){
        const file = path.join(src_dir, name);
        const source = await readFile(file, 'utf8');

        // Not every SVG at static/'s root is one of the drawings, and this
        // pipeline is only meaningful for something with a viewBox to
        // normalize against: one without ships as authored. That is as far
        // as the tolerance goes. Anything *with* a viewBox is taken for a
        // drawing, and a stray decorative SVG -- assets/icon.svg has one,
        // make-icons.mjs requires it -- stops the build, and with it the
        // deploy, at its first non-<path> element. Failing loudly beats
        // shipping art this pipeline was never meant for; it does mean
        // static/'s root is not a dumping ground for icons.
        if (!VIEWBOX.test(source)){
            await writeFile(path.join(out_dir, name), source);
            copied++;
            continue;
        }

        keep.add(cache_key(source));
        const data = await cached_svg(source, () => {
            const collapsed = svgo_pass(source, file, 4);   // structure, not size
            return svgo_pass(normalize_svg(collapsed, name), file, 0);
        });

        // A plugin that drops viewBox turns an <img> sized by CSS height into
        // one that ignores its aspect ratio. preset-default does not, today --
        // this is here so that a future svgo has to fail the build rather than
        // quietly reshape 54 portraits.
        if (source.includes('viewBox') && !data.includes('viewBox')){
            throw new Error(`svgo dropped the viewBox from ${name}`);
        }
        before += Buffer.byteLength(source);
        after += Buffer.byteLength(data);
        await writeFile(path.join(out_dir, name), data);
    }
    await prune_svg_cache(keep);
    return { files: names.length, drawings: names.length - copied, copied, before, after };
}

// Everything a browser needs to install the site, derived from the manifest so
// there is one source of truth for the values -- but repeated as <meta> tags
// because iOS ignores the manifest entirely.
//
// iOS wants exactly ONE apple-touch-icon, at 180x180. This used to emit a link
// for every icon in the manifest, and every one of those icons had a
// transparent background -- which iOS composites against *black*, so the home
// screen showed the wheel on a black tile.
function app_meta(manifest){
    const required = ['name', 'short_name', 'start_url', 'display',
                      'theme_color', 'background_color'];
    for (const field of required){
        if (!manifest[field]) throw new Error(`manifest is missing ${field}`);
    }
    // checked before it is walked: an absent icons array would otherwise fail
    // with a TypeError instead of something that says what to do about it
    if (!Array.isArray(manifest.icons) || manifest.icons.length === 0){
        throw new Error('manifest lists no icons: run `npm run icons`');
    }
    if (!manifest.icons.some(i => i.purpose === 'maskable')){
        // without one, Android crops the artwork to its launcher shape and
        // clips the wheel's rim; see scripts/make-icons.mjs
        throw new Error('manifest has no maskable icon: run `npm run icons`');
    }
    const touch = manifest.icons.find(i => i.sizes === '180x180' && i.purpose !== 'maskable');
    if (!touch) throw new Error('manifest has no 180x180 icon for apple-touch-icon');

    return `<meta name="theme-color" content="${xml_escape(manifest.theme_color)}"/>`
        + '<meta name="mobile-web-app-capable" content="yes"/>'
        // the apple- prefix is deprecated in favour of the line above, but
        // older iOS still reads only this one
        + '<meta name="apple-mobile-web-app-capable" content="yes"/>'
        + `<meta name="apple-mobile-web-app-title" content="${xml_escape(manifest.name)}"/>`
        + `<link rel="apple-touch-icon" sizes="${touch.sizes}" href="${touch.src}"/>`;
}

function xml_escape(s){
    return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
            .replace(/"/g, '&quot;').replace(/'/g, '&apos;');
}

// JSON that is safe to embed in a script regardless of context
function script_json(value){
    return JSON.stringify(value).replace(/</g, '\\u003c');
}

// pwa.md Phase 4: hosted GoatCounter, cookie-free and consent-banner-free.
// `async` and last in the body, so it is fetched after the page has parsed and
// after the site's own scripts have run -- analytics never sits on the critical
// path, and a slow or unreachable gc.zgo.at delays nothing.
//
// count.js declines to count from localhost, from file:// and from RFC-1918
// addresses on its own, so `npm run serve` and a build opened off disk stay out
// of the dashboard for free. A Netlify deploy preview does not: it is a real
// host on a real domain, and its hits land in the same dashboard as
// production's, with nothing to tell them apart afterwards.
//
// That is a known and accepted cost, Jason's call (pwa.md Phase 4): he tests
// against production anyway, so his own clicks are in the numbers either way,
// and the site should have enough real traffic to dilute them. Keeping the tag
// on every host also means a preview URL can answer "does a hit land", which is
// the only place Phase 4's verification can be rehearsed before a merge. A
// CONTEXT-based gate was tried and reverted -- do not re-add it without asking.
//
// To keep one browser out of the numbers for good, load any page with
// #toggle-goatcounter; count.js stores the opt-out in localStorage.
function analytics_tag(endpoint, src){
    return `<script data-goatcounter="${xml_escape(endpoint)}" async src="${xml_escape(src)}"></script>`;
}

function page_html({ head, body, scripts }, css, app, analytics){
    return '<!DOCTYPE html><html lang="en"><head>'
        + '<meta charset="utf-8"/>'
        + '<meta http-equiv="x-ua-compatible" content="ie=edge"/>'
        // viewport-fit=cover lets the page paint into the notch/home-indicator
        // area; it only works paired with the env(safe-area-inset-*) padding on
        // .container in layout.module.css -- one without the other either clips
        // content under the notch or wastes the inset.
        + '<meta name="viewport" content="width=device-width, initial-scale=1, shrink-to-fit=no, viewport-fit=cover"/>'
        // the site is light-only until pwa.md Phase 6 decides on dark mode.
        // Saying so stops the browser from painting a dark canvas behind a
        // light page (a white flash, or worse, dark form controls on it).
        + '<meta name="color-scheme" content="light"/>'
        + head
        + `<style>${css}</style>`
        + '<link rel="icon" href="/favicon-32x32.png" type="image/png"/>'
        + '<link rel="manifest" href="/manifest.webmanifest" crossorigin="anonymous"/>'
        + app
        + '<link rel="sitemap" type="application/xml" href="/sitemap/sitemap-index.xml"/>'
        + '</head><body>'
        + body
        + (scripts || '')
        + analytics
        + '</body></html>';
}

function sitemap_xml(site_url, paths){
    const urls = paths.map(p =>
        `<url><loc>${xml_escape(site_url + p)}</loc><changefreq>daily</changefreq><priority>0.7</priority></url>`
    ).join('');
    return {
        'sitemap-index.xml': '<?xml version="1.0" encoding="UTF-8"?>'
            + '<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">'
            + `<sitemap><loc>${xml_escape(site_url)}/sitemap/sitemap-0.xml</loc></sitemap>`
            + '</sitemapindex>',
        'sitemap-0.xml': '<?xml version="1.0" encoding="UTF-8"?>'
            + '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">'
            + urls
            + '</urlset>',
    };
}

async function build(){
    await rm(dist, { recursive: true, force: true });
    // not the whole of .cache: svg/ is a content-addressed cache worth keeping
    // between builds (see minify_svgs). ssg/ is scratch and goes.
    await rm(ssr, { recursive: true, force: true });

    // install metadata + the apple-touch-icon link, derived from the manifest
    // so there is one source of truth for the icon set and the theme colour
    const manifest = JSON.parse(await readFile(path.join(root, 'static', 'manifest.webmanifest'), 'utf8'));
    const app = app_meta(manifest);

    // 1. Bundle the SSR entry (JSX + CSS modules + data.json) for Node.
    await esbuild.build({
        entryPoints: [path.join(root, 'scripts', 'render.js')],
        bundle: true,
        platform: 'node',
        format: 'esm',
        packages: 'external', // react/react-dom resolve from node_modules
        loader: { '.js': 'jsx' },
        target: 'node22', // the engines floor, not .nvmrc: this must run
                          // on the oldest Node we claim to support
        outdir: ssr,
        outExtension: { '.js': '.mjs' },
    });

    const { CLASS_NAMES, GC_ENDPOINT, GC_PLAY_EVENT, GC_SCRIPT, SITE_TITLE, SITE_URL,
            random_targets, render_pages } =
        await import(pathToFileURL(path.join(ssr, 'render.mjs')));

    const analytics = analytics_tag(GC_ENDPOINT, GC_SCRIPT);

    // 2. The bundle's CSS output (all modules' styles) gets inlined into
    // every page, as Gatsby did.
    const raw_css = await readFile(path.join(ssr, 'render.css'), 'utf8');
    const css = (await esbuild.transform(raw_css, {
        loader: 'css',
        minify: true,
        target: BROWSER_TARGET,
    })).code.trim();

    // 3. Client scripts: the play-control click handler for work pages and
    // the 🔀-link randomizer, which every page loads for its nav links.
    //
    // The nav's two 🔀 lists are baked into shuffle.js rather than into every
    // page's markup -- see src/client/shuffle.js. Same random_targets() the
    // redirect pages below use, so the two can't disagree.
    const targets = random_targets();
    await esbuild.build({
        entryPoints: [
            path.join(root, 'src', 'client', 'work.js'),
            path.join(root, 'src', 'client', 'shuffle.js'),
        ],
        bundle: true,
        minify: true,
        target: BROWSER_TARGET,
        define: {
            TABLE_PLAYING: script_json(CLASS_NAMES.tablePlaying),
            PLAY_ICON: script_json(CLASS_NAMES.playIcon),
            PLAYER_BOX: script_json(CLASS_NAMES.playerBox),
            CLOSE_PLAYER: script_json(CLASS_NAMES.closePlayer),
            PLAY_EVENT: script_json(GC_PLAY_EVENT),
            SHUFFLE_TARGETS: script_json(targets),
        },
        outdir: path.join(dist, 'js'),
    });

    // 4. The redirect pages, kept as entry points for typed and bookmarked
    // URLs; in-site 🔀 clicks never come here. Thin on purpose: no layout,
    // no stylesheet, script inlined so the redirect fires during parse -- and
    // no analytics tag either: fetching count.js to count a page that replaces
    // itself in the same tick would slow down the only thing these do, and the
    // page they land on counts the visit a moment later anyway.
    const redirects = [
        { path: '/random', title: 'Random Quartet', slugs: targets['random'] },
        { path: '/random-composer', title: 'Random Composer', slugs: targets['random-composer'] },
    ];
    for (const r of redirects){
        const html = '<!DOCTYPE html><html lang="en"><head><meta charset="utf-8"/>'
            + `<title>${r.title} | ${SITE_TITLE}</title>`
            + `<script>var t=${script_json(r.slugs)};location.replace(t[Math.floor(Math.random()*t.length)]);</script>`
            + '</head><body></body></html>';
        const dir = path.join(dist, ...r.path.split('/').filter(Boolean));
        await mkdir(dir, { recursive: true });
        await writeFile(path.join(dir, 'index.html'), html);
    }

    // 5. Render every page. The nav's 🔀 links carry data-shuffle-key on every
    // page (the lists themselves live in shuffle.js), so every page loads it.
    const pages = render_pages();
    for (const page of pages){
        let scripts = '<script src="/js/shuffle.js"></script>';
        if (page.component === 'work'){
            scripts += '<script src="/js/work.js"></script>';
        }
        const dir = path.join(dist, ...page.path.split('/').filter(Boolean));
        // page paths come from data.json names/catalogs; never write outside dist/
        if (!(dir + path.sep).startsWith(dist + path.sep)){
            throw new Error(`page path escapes dist/: ${page.path}`);
        }
        await mkdir(dir, { recursive: true });
        const html = page_html({ ...page, scripts }, css, app, analytics);
        await writeFile(path.join(dir, 'index.html'), html);
        if (page.path === '/404/'){
            await writeFile(path.join(dist, '404.html'), html); // Netlify's custom 404
        }
    }

    // 6. Sitemap: every rendered page except /404/, at the same URL as
    // gatsby-plugin-sitemap. The redirect pages are deliberately absent —
    // they exist to be typed and bookmarked, not to be indexed as blanks.
    const sitemap = sitemap_xml(SITE_URL, pages.map(p => p.path).filter(p => p !== '/404/'));
    await mkdir(path.join(dist, 'sitemap'), { recursive: true });
    for (const [name, xml] of Object.entries(sitemap)){
        await writeFile(path.join(dist, 'sitemap', name), xml);
    }

    // 7. Static assets, copied through -- but the share cards get their size
    // checked on the way past, and the portraits get minified.
    const card_count = await check_og_cards(path.join(root, 'static', 'og'));
    const static_dir = path.join(root, 'static');
    await cp(static_dir, dist, {
        recursive: true,
        // the drawings are not copied: minify_svgs writes them instead
        filter: src => path.basename(src) !== '.DS_Store' && !src.endsWith('.svg'),
    });
    const svg = await minify_svgs(static_dir, dist);
    // minify_svgs only looks at static/'s top level, which is where all 54
    // live. A drawing added in a subdirectory would be skipped by the copy
    // above and never written by minify_svgs -- so it would silently vanish
    // from the site rather than fail. Count them and complain instead.
    const all_svgs = (await readdir(static_dir, { recursive: true }))
        .filter(f => f.endsWith('.svg')).length;
    if (all_svgs !== svg.files){
        throw new Error(`${all_svgs - svg.files} SVG(s) live in a subdirectory of static/;`
            + ' minify_svgs only handles the top level');
    }

    // name the directory actually written: this script takes the output as
    // an argument, and the test builds and sub-builds use it
    const where = dist.startsWith(root + path.sep) ? path.relative(root, dist) : dist;
    console.log(`built ${pages.length + redirects.length} pages to ${where}/`
        + ` (${card_count} share cards under ${OG_MAX_BYTES.toLocaleString()} bytes;`
        + ` ${svg.drawings} drawings ${(svg.before/1024).toFixed(0)} KB`
        + ` -> ${(svg.after/1024).toFixed(0)} KB`
        + (svg.copied ? `; ${svg.copied} SVG(s) copied as-is` : '') + ')');
}

// Success or failure, this run's SSR scratch must not outlive it. The
// per-output namespacing means no other build ever sweeps it -- a test
// build's directory name is minted fresh per run -- so a build that threw
// partway (a bad drawing, an oversized share card, an esbuild error) would
// otherwise leak one .cache/ssg-* directory per failure, forever.
try {
    await build();
} finally {
    await rm(ssr, { recursive: true, force: true });
}
